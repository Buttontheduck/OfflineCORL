"""Handoff test (EqM_RL.md, "Planned next experiments", section 5a): do flips depend more on who
generated the state, or on who acts after it?

1. Source rollouts: --n_eps episodes of Gaussian AWAC (its mean action) and of Aware (one EqM
   sample per step at the trained sampler setting), env seeds seed0, seed0 + 1, ...  The full
   MuJoCo state (qpos, qvel) is saved after each step count in --at.
2. Continuations: every saved state is put into a freshly reset env and continued for the same
   --horizon steps by AWAC (once: its mean action and HalfCheetah's physics are deterministic)
   and by Aware (--n_rep times, with different sampler noise):

       state generated by | continued by AWAC | continued by Aware
       AWAC               | control           | handoff
       Aware              | handoff           | control

   All four cells use the same restore procedure, so restoring can't explain a difference.
States where a flip already happened (body angle beyond --flip_angle at any step up to the save)
are reported separately from upright states. Per continuation: flip within the horizon, return
over the horizon, mean speed. Aware's continuations of one state are averaged first, so every
saved state counts once.
Restore check, before the continuations: every saved state of both sources is restored into a
fresh env and stepped with the source's own recorded actions for --replay_steps steps; every
observation must match the source rollout within --restore_tol. HalfCheetah's physics are
deterministic; the differences seen are ~1e-11, most likely from MuJoCo's solver warm start,
which (qpos, qvel) doesn't include. Otherwise the script stops and saves nothing. `awac_policy_first_step_diff` is for information only: AWAC re-computing its action on
a restored state in a different batch (GPU batch sizes can change the last digits).

    python diagnostics/handoff.py <Aware run dir> <AWAC run dir of the same seed> \
        diagnostics/out/handoff/<name>.json
"""

import argparse
import json
import time
from pathlib import Path

import numpy as np
import torch

from common import AwacPolicy, Policy, get_sim_state, set_sim_state

ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
ap.add_argument("run_dir", type=Path, help="checkpoint folder of one Aware run (has config.yaml)")
ap.add_argument("awac", type=Path, help="checkpoint folder of the Gaussian on the same dataset: a CORL AWAC run "
                "or a fit_actor.py Gaussian fit")
ap.add_argument("out", type=Path, help="output JSON")
ap.add_argument("--checkpoint", help="Aware checkpoint file name, default: the latest")
ap.add_argument("--at", default="100,300,500", help="handoff points: env steps taken before the switch")
ap.add_argument("--horizon", type=int, default=200, help="steps after the switch, the same for every cell")
ap.add_argument("--n_eps", type=int, default=20, help="source episodes per policy")
ap.add_argument("--n_rep", type=int, default=4, help="Aware continuations per saved state (sampler noise)")
ap.add_argument("--seed0", type=int, default=69, help="env seed of the first source episode")
ap.add_argument("--flip_angle", type=float, default=2.0, help="|body angle| in rad that counts as a flip")
ap.add_argument("--replay_steps", type=int, default=20, help="steps of the restore check (recorded actions replayed)")
ap.add_argument("--restore_tol", type=float, default=1e-6, help="largest accepted |obs difference| in the restore check")
args = ap.parse_args()
t0 = time.time()

pol = Policy(args.run_dir, args.checkpoint)
awac = AwacPolicy(args.awac, pol)
torch.manual_seed(0)
at = sorted(int(v) for v in args.at.split(","))
H, n_eps, R = args.horizon, args.n_eps, args.replay_steps
if any(b - a < R for a, b in zip(at, at[1:])):
    raise SystemExit(f"handoff points {at} must be at least --replay_steps ({R}) apart")
ACT = {"awac": awac.act, "aware": pol.act}


def run(envs, obs, who, steps, actions=None):
    """Step every env `steps` times; who[i] names the policy of env i, or `actions` (steps, n, ad)
    gives the actions to replay. Returns the per-step body angle, speed and reward, each
    (steps, len(envs)), the observations after every step and the executed actions."""
    obs = obs.copy()
    groups = [(name, np.flatnonzero(who == name)) for name in ACT] if who is not None else []
    ang, spd, rew, hist, acts = [], [], [], [], []
    for k in range(steps):
        if actions is not None:
            a = actions[k]
        else:
            S = pol.states(obs)
            a = np.zeros((len(envs), pol.action_dim))
            for name, rows in groups:
                if len(rows):
                    a[rows] = ACT[name](S[rows]).cpu().numpy()
        r = np.zeros(len(envs))
        for i, e in enumerate(envs):
            obs[i], r[i], _ = pol.step(e, a[i])
        ang.append(obs[:, 1].copy())
        spd.append(obs[:, 8].copy())
        rew.append(r)
        hist.append(obs.copy())
        acts.append(np.array(a, copy=True))
    return np.array(ang), np.array(spd), np.array(rew), np.array(hist), np.array(acts)


def restore_all(states):
    """Fresh envs, reset and then set to the given states; -> envs, their observations."""
    envs = [pol.make_env() for _ in states]
    obs = np.zeros((len(states), pol.state_dim))
    for i, (e, st) in enumerate(zip(envs, states)):
        pol.reset(e, 0)
        obs[i] = set_sim_state(e, st)
    return envs, obs


# ---------------------------------------------------------------- 1. source rollouts
sources = {}   # (source, t) -> saved states, flip-before flags, the source's next R actions and obs
for src in ("awac", "aware"):
    envs = [pol.make_env() for _ in range(n_eps)]
    obs = np.stack([pol.reset(e, args.seed0 + j) for j, e in enumerate(envs)]).astype(np.float64)
    who = np.full(n_eps, src)
    angs, done_steps = [], 0
    for t in at:
        if t > done_steps:
            ang, _, _, hist, _ = run(envs, obs, who, t - done_steps)
            angs.append(ang)
            obs = hist[-1]
        states = [get_sim_state(e) for e in envs]
        flipped_before = (np.abs(np.concatenate(angs)) > args.flip_angle).any(0) if angs else np.zeros(n_eps, bool)
        # the source goes on for R steps; their actions and observations are the restore check
        ang, _, _, hist, acts = run(envs, obs, who, R)
        angs.append(ang)
        obs = hist[-1]
        done_steps = t + R
        sources[(src, t)] = dict(states=states, flipped_before=flipped_before, replay_actions=acts, replay_obs=hist)
    del envs

# ---------------------------------------------------------------- restore check (fail before the long part)
replay_diff = 0.0
for (src, t), s in sources.items():
    envs, obs = restore_all(s["states"])
    _, _, _, hist, _ = run(envs, obs, None, R, actions=s["replay_actions"])
    del envs
    diff = np.abs(hist - s["replay_obs"])
    # NaN never compares as larger, so max(0.0, nan) would be 0.0: check finiteness first
    if not np.isfinite(diff).all():
        raise SystemExit(f"restore check failed: non-finite observations when replaying {src} states saved "
                         f"at step {t}. Nothing saved.")
    replay_diff = max(replay_diff, float(diff.max()))
if not replay_diff <= args.restore_tol:
    raise SystemExit(f"restore check failed: replaying the recorded actions from restored states differs by "
                     f"{replay_diff:.3e} > --restore_tol {args.restore_tol:g}. Nothing saved.")

# ---------------------------------------------------------------- 2. continuations
cells = []  # (source, t, episode, continuation policy, rep)
for (src, t) in sources:
    for j in range(n_eps):
        cells.append((src, t, j, "awac", 0))
        cells += [(src, t, j, "aware", k) for k in range(args.n_rep)]
envs, obs = restore_all([sources[(c[0], c[1])]["states"][c[2]] for c in cells])
who = np.array([c[3] for c in cells])
ang, spd, rew, hist, _ = run(envs, obs, who, H)
del envs
flip_c = (np.abs(ang) > args.flip_angle).any(0)
flip_step_c = np.where(flip_c, (np.abs(ang) > args.flip_angle).argmax(0), -1)
ret_c, spd_c = rew.sum(0), spd.mean(0)

# information only: AWAC re-computing its action on a restored AWAC state, in a different batch
policy_diff = float(np.max([np.abs(hist[0][i] - sources[(c[0], c[1])]["replay_obs"][0][c[2]]).max()
                             for i, c in enumerate(cells) if c[0] == "awac" and c[3] == "awac"]))  # NaN stays NaN

# ---------------------------------------------------------------- per state, then per cell
res = dict(pol.info(), awac_run=args.awac.name, awac_kind=awac.kind,
           args={k: str(v) for k, v in vars(args).items()},
           restore_check_max_abs_diff=replay_diff, awac_policy_first_step_diff=policy_diff, cells={}, states=[])
for (src, t), s in sources.items():
    for cont in ("awac", "aware"):
        f, rt, sp, fs = [], [], [], []
        for j in range(n_eps):
            idx = [i for i, c in enumerate(cells) if c[:4] == (src, t, j, cont)]
            f.append(flip_c[idx].mean())
            rt.append(ret_c[idx].mean())
            sp.append(spd_c[idx].mean())
            fs.append([int(v) for v in flip_step_c[idx]])
        f, rt, sp, fb = map(np.array, (f, rt, sp, s["flipped_before"]))
        up = ~fb
        res["cells"][f"{src}->{cont}@{t}"] = dict(
            source=src, continued_by=cont, t=t, n_upright=int(up.sum()), n_flipped_before=int(fb.sum()),
            flip_rate_upright=float(f[up].mean()) if up.any() else None,
            return_upright=float(rt[up].mean()) if up.any() else None,
            speed_upright=float(sp[up].mean()) if up.any() else None,
            return_flipped_before=float(rt[fb].mean()) if fb.any() else None,
            speed_flipped_before=float(sp[fb].mean()) if fb.any() else None)
        for j in range(n_eps):
            res["states"].append(dict(source=src, t=t, episode=j, continued_by=cont,
                                      flipped_before=bool(fb[j]), flip_prob=float(f[j]),
                                      flip_steps=fs[j], ret=float(rt[j]), speed=float(sp[j])))

res["minutes"] = (time.time() - t0) / 60
args.out.parent.mkdir(parents=True, exist_ok=True)
args.out.write_text(json.dumps(res))

print(f"{pol.run_dir.name} vs {args.awac.name}  ({res['minutes']:.1f} min; horizon {H}; restore check "
      f"over {R} replayed steps: max |diff| {replay_diff:.1e}; AWAC recomputed first step {policy_diff:.1e})")
print(f"{'cell':<20}{'upright':>8}{'flips':>8}{'return':>9}{'speed':>7}{'flipped before':>16}")
for name, c in res["cells"].items():
    fr = "-" if c["flip_rate_upright"] is None else f"{c['flip_rate_upright']:.0%}"
    rt = "-" if c["return_upright"] is None else f"{c['return_upright']:.0f}"
    sp = "-" if c["speed_upright"] is None else f"{c['speed_upright']:.2f}"
    print(f"{name:<20}{c['n_upright']:>8}{fr:>8}{rt:>9}{sp:>7}{c['n_flipped_before']:>16}")
